#!/usr/bin/env node
/**
 * Emits the file-tree icon sprite and lookup tables from the vendored Catppuccin icon set.
 *
 * Reads  src/renderer/assets/file-icons/vendor
 * Writes src/renderer/assets/file-icons/generated
 * Offline and idempotent. Re-vendor with scripts/sync-file-icons.mjs.
 */
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const SVG_SUFFIX = '.svg';
const SYMBOL_ID_PREFIX = 'fi-';
const FOLDER_ICON_PREFIX = 'folder_';
const CURRENT_COLOR = 'currentColor';
const DEFAULT_VIEW_BOX = '0 0 16 16';
const JSON_INDENT = 2;

const CTP_COLOR_PATTERN = /var\(--vscode-ctp-([a-z0-9]+)\)/g;
const COLOR_ATTRIBUTE_PATTERN = /(?:fill|flood-color|lighting-color|stop-color|stroke)="([^"]*)"/g;
const SVG_OPEN_TAG_PATTERN = /^[\s\S]*?<svg[^>]*>/;
const SVG_CLOSE_TAG_PATTERN = /<\/svg>\s*$/;
const VIEW_BOX_PATTERN = /viewBox="([^"]+)"/;
const ID_ATTRIBUTE_PATTERN = /id="([^"]+)"/g;
const ID_REFERENCE_PATTERN = /url\(#([^)]+)\)/g;
const WHITESPACE_PATTERN = /\s*\n\s*/g;

/** Presentation attributes hoisted onto the rendering <svg>; <use> shadow trees inherit them. */
const INHERITED_ATTRIBUTES = [
  ' fill="none"',
  ` stroke="${CURRENT_COLOR}"`,
  ' stroke-linecap="round"',
  ' stroke-linejoin="round"',
];

/** Catppuccin palette entries that carry no hue; used only when an icon has no chromatic stroke. */
const NEUTRAL_PALETTES = new Set([
  'base', 'crust', 'mantle', 'overlay0', 'overlay1', 'overlay2', 'subtext0', 'subtext1',
  'surface0', 'surface1', 'surface2', 'text',
]);

const desktopRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const assetsDir = join(desktopRoot, 'src/renderer/assets/file-icons');
const vendorDir = join(assetsDir, 'vendor');
const generatedDir = join(assetsDir, 'generated');

const GENERATED_HEADER = [
  '// Generated by desktop/scripts/generate-file-icons.mjs — do not edit.',
  '// Icon artwork: Catppuccin VS Code Icons (MIT), see ../vendor/LICENSE.',
].join('\n');

function readVendorAssociations(fileName) {
  return JSON.parse(readFileSync(join(vendorDir, fileName), 'utf8')).icons;
}

function readVendorIconIds() {
  return readdirSync(join(vendorDir, 'icons'))
    .filter((entry) => entry.endsWith(SVG_SUFFIX))
    .map((entry) => entry.slice(0, -SVG_SUFFIX.length))
    .sort();
}

function countPaletteUsage(markup) {
  const counts = new Map();
  for (const [, name] of markup.matchAll(CTP_COLOR_PATTERN)) {
    counts.set(name, (counts.get(name) ?? 0) + 1);
  }
  return counts;
}

function mostUsedPalette(counts) {
  return [...counts.entries()]
    .sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]))
    .map(([name]) => name)[0];
}

function resolvePalette(markup) {
  const counts = countPaletteUsage(markup);
  const chromatic = new Map([...counts].filter(([name]) => !NEUTRAL_PALETTES.has(name)));
  return mostUsedPalette(chromatic.size > 0 ? chromatic : counts) ?? 'text';
}

function namespaceInternalIds(markup, iconId) {
  return markup
    .replace(ID_ATTRIBUTE_PATTERN, `id="${iconId}-$1"`)
    .replace(ID_REFERENCE_PATTERN, `url(#${iconId}-$1)`);
}

function stripInheritedAttributes(markup) {
  return INHERITED_ATTRIBUTES.reduce(
    (result, attribute) => result.split(attribute).join(''),
    markup,
  );
}

/**
 * Any paint that is not `currentColor`, `none` or a local reference stays fixed across themes.
 * Reporting it here stops an upstream sync from silently reintroducing a theme-blind glyph.
 */
function findFixedColors(markup) {
  const values = new Set();
  for (const [, value] of markup.matchAll(COLOR_ATTRIBUTE_PATTERN)) {
    if (value === CURRENT_COLOR || value === 'none' || value.startsWith('url(#')) continue;
    values.add(value);
  }
  return [...values];
}

function buildSymbol(iconId) {
  const source = readFileSync(join(vendorDir, 'icons', `${iconId}${SVG_SUFFIX}`), 'utf8');
  const viewBox = source.match(VIEW_BOX_PATTERN)?.[1] ?? DEFAULT_VIEW_BOX;
  const body = source.replace(SVG_OPEN_TAG_PATTERN, '').replace(SVG_CLOSE_TAG_PATTERN, '');
  const normalized = stripInheritedAttributes(
    namespaceInternalIds(body.replace(CTP_COLOR_PATTERN, CURRENT_COLOR), iconId),
  ).replace(WHITESPACE_PATTERN, '').trim();

  return {
    fixedColors: findFixedColors(normalized),
    markup: `<symbol id="${SYMBOL_ID_PREFIX}${iconId}" viewBox="${viewBox}">${normalized}</symbol>`,
    palette: resolvePalette(body),
  };
}

function reportThemeBlindIcons(offenders) {
  if (offenders.length === 0) return;
  const detail = offenders.map(({ colors, iconId }) => `  ${iconId}: ${colors.join(', ')}`).join('\n');
  process.stderr.write(
    `Theme-blind icons found; exclude them in scripts/sync-file-icons.mjs and re-sync:\n${detail}\n`,
  );
  process.exit(1);
}

function buildAssociationMap(associations, vendoredIds, field) {
  const entries = [];
  for (const [iconId, association] of Object.entries(associations)) {
    if (!vendoredIds.has(iconId)) continue;
    for (const key of association[field] ?? []) {
      entries.push([key.toLowerCase(), iconId]);
    }
  }
  return Object.fromEntries(entries.sort(([a], [b]) => a.localeCompare(b)));
}

function buildFolderMap(associations, vendoredIds) {
  const entries = [];
  for (const [iconId, association] of Object.entries(associations)) {
    const symbolIcon = `${FOLDER_ICON_PREFIX}${iconId}`;
    if (!vendoredIds.has(symbolIcon)) continue;
    for (const key of association.folderNames ?? []) {
      entries.push([key.toLowerCase(), symbolIcon]);
    }
  }
  return Object.fromEntries(entries.sort(([a], [b]) => a.localeCompare(b)));
}

function serializeMap(name, map) {
  return `export const ${name}: Readonly<Record<string, string>> = ${JSON.stringify(map, null, JSON_INDENT)};`;
}

function serializePalettes(palettes) {
  const names = [...new Set(Object.values(palettes))].sort();
  const union = names.map((name) => `'${name}'`).join('\n  | ');
  return [
    `export type FileIconPalette =\n  | ${union};`,
    '',
    `export const FILE_ICON_PALETTES: Readonly<Record<string, FileIconPalette>> = ${JSON.stringify(palettes, null, JSON_INDENT)};`,
  ].join('\n');
}

const fileAssociations = readVendorAssociations('file-associations.json');
const folderAssociations = readVendorAssociations('folder-associations.json');
const iconIds = readVendorIconIds();
const vendoredIds = new Set(iconIds);

const symbols = [];
const palettes = {};
const themeBlindIcons = [];
for (const iconId of iconIds) {
  const symbol = buildSymbol(iconId);
  symbols.push(symbol.markup);
  palettes[iconId] = symbol.palette;
  if (symbol.fixedColors.length > 0) {
    themeBlindIcons.push({ colors: symbol.fixedColors, iconId });
  }
}
reportThemeBlindIcons(themeBlindIcons);

const sprite = [
  '<svg xmlns="http://www.w3.org/2000/svg" width="0" height="0" aria-hidden="true">',
  ...symbols,
  '</svg>',
  '',
].join('\n');

const lookupModule = [
  GENERATED_HEADER,
  '',
  serializeMap('FILE_ICON_NAMES', buildAssociationMap(fileAssociations, vendoredIds, 'fileNames')),
  '',
  serializeMap('FILE_ICON_EXTENSIONS', buildAssociationMap(fileAssociations, vendoredIds, 'fileExtensions')),
  '',
  serializeMap('FOLDER_ICON_NAMES', buildFolderMap(folderAssociations, vendoredIds)),
  '',
  serializePalettes(palettes),
  '',
].join('\n');

mkdirSync(generatedDir, { recursive: true });
writeFileSync(join(generatedDir, 'file-icon-sprite.svg'), sprite);
writeFileSync(join(generatedDir, 'fileIconMaps.ts'), lookupModule);

process.stdout.write(
  `Generated ${symbols.length} symbols, sprite ${(Buffer.byteLength(sprite) / 1024).toFixed(1)}KB\n`,
);
